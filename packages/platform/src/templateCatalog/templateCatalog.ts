/**
 * The template catalog (0.3.1).
 *
 * The template convention since 0.3.1: a template's CODE is immutable once it
 * ships. What describes it without changing what it renders — label,
 * description, tags, platforms, channels, preview, internal,
 * primitive, deprecated (`MOSAIC_TEMPLATE_CATALOG_FIELDS`) and each prop's
 * presentation (`MOSAIC_TEMPLATE_PROP_CATALOG_FIELDS`: label, hint, placeholder,
 * order, …) — lives in the template's catalog sidecar, because it may change
 * after the template ships.
 *
 * Two files, one shape:
 *   - `<name>.catalog.json` beside the template's module — the AUTHORING form,
 *     one per template (`MosaicTemplateCatalogSidecar`); a freeze hashes code,
 *     never this, so it stays editable after the code freezes;
 *   - `template-catalog.json` at the repo root beside `template-manifest.json`
 *     — the WIRE form (`MosaicTemplateCatalogFile`), generated by the repo's
 *     build from the sidecars; the one file a host reads (zero-exec, signed
 *     with a community release).
 *
 * Browser-safe on purpose (no node builtins): the official pack's web entry
 * parses its catalog with this, and the node-only repo loader and sidecar
 * collector (`template-repos/`) use the same parser and merge.
 */
import type {
  MosaicTemplateCatalogEntry,
  MosaicTemplateCatalogField,
  MosaicTemplateCatalogFile,
  MosaicTemplateDeprecation,
  MosaicTemplatePropCatalog,
} from "@m0saic/types";
import { MOSAIC_TEMPLATE_CATALOG_FIELDS, MOSAIC_TEMPLATE_PROP_CATALOG_FIELDS, asTemplateId } from "@m0saic/types";

/** The WIRE catalog's file name, at a repo's root beside `template-manifest.json`. */
export const TEMPLATE_CATALOG_FILE = "template-catalog.json";

/** A template's catalog SIDECAR ends in this, beside the template's module (`quote-card.catalog.json`). */
export const TEMPLATE_CATALOG_SIDECAR_SUFFIX = ".catalog.json";

/**
 * Where a catalog-merged template keeps what its own module declared — the
 * catalog fields and the original `propsSchema` — so the registry can still pin
 * and audit the template as WRITTEN. `Symbol.for` so template-utils reads it
 * without importing this module.
 */
export const TEMPLATE_CATALOG_AUTHORED_KEY = Symbol.for("m0saic.templateCatalogAuthored");

type Authored = { fields: Partial<Record<MosaicTemplateCatalogField, unknown>>; propsSchema: unknown };

const CATALOG_FIELDS = new Set<string>([...MOSAIC_TEMPLATE_CATALOG_FIELDS, "props"]);
const PROP_FIELDS = new Set<string>(MOSAIC_TEMPLATE_PROP_CATALOG_FIELDS);
const DEPRECATION_KEYS = new Set(["reason", "replacement", "since"]);
const ISO_DAY = /^\d{4}-\d{2}-\d{2}$/;

const isRecord = (v: unknown): v is Record<string, unknown> =>
  v !== null && typeof v === "object" && !Array.isArray(v);
const isStringList = (v: unknown): v is string[] =>
  Array.isArray(v) && v.every((x) => typeof x === "string" && x.trim().length > 0);
const nonEmpty = (v: unknown): v is string => typeof v === "string" && v.trim().length > 0;

/* ── parsing ─────────────────────────────────────────────────────────────── */

function parseDeprecation(where: string, value: unknown, problems: string[]): MosaicTemplateDeprecation | null {
  if (!isRecord(value)) {
    problems.push(`${where}: "deprecated" must be an object ({ reason, replacement?, since }) — dropped`);
    return null;
  }
  const out: MosaicTemplateDeprecation = {};
  for (const key of Object.keys(value)) {
    if (!DEPRECATION_KEYS.has(key)) problems.push(`${where}: deprecated has an unknown key "${key}" — it carries reason, replacement and since only`);
  }
  if (nonEmpty(value.reason)) out.reason = value.reason;
  else problems.push(`${where}: deprecated.reason must say why the template is superseded`);
  if (value.replacement !== undefined) {
    if (nonEmpty(value.replacement)) out.replacement = asTemplateId(value.replacement);
    else problems.push(`${where}: deprecated.replacement must be a template id — dropped`);
  }
  if (typeof value.since === "string" && ISO_DAY.test(value.since)) out.since = value.since;
  else problems.push(`${where}: deprecated.since must be the day it was declared (YYYY-MM-DD)`);
  return out;
}

function parsePropCatalog(where: string, value: unknown, problems: string[]): MosaicTemplatePropCatalog | null {
  if (!isRecord(value)) {
    problems.push(`${where}: a prop entry must be an object of presentation fields — dropped`);
    return null;
  }
  const out: MosaicTemplatePropCatalog = {};
  for (const [key, v] of Object.entries(value)) {
    if (!PROP_FIELDS.has(key)) {
      problems.push(`${where}: "${key}" is not a prop presentation field (${MOSAIC_TEMPLATE_PROP_CATALOG_FIELDS.join(", ")}) — what a value IS stays in the template`);
      continue;
    }
    switch (key) {
      case "label":
      case "description":
      case "placeholder":
        if (nonEmpty(v)) out[key] = v;
        else problems.push(`${where}.${key} must be a non-empty string — dropped`);
        break;
      case "order":
        if (typeof v === "number" && Number.isFinite(v)) out.order = v;
        else problems.push(`${where}.order must be a number — dropped`);
        break;
      case "primary":
      case "collapsedByDefault":
        if (typeof v === "boolean") out[key] = v;
        else problems.push(`${where}.${key} must be true or false — dropped`);
        break;
    }
  }
  return out;
}

/**
 * Parse one template's catalog entry (the fields of a sidecar, or one value of
 * the wire file's `templates`). Lenient — a malformed field is dropped and
 * REPORTED, never thrown: a host loading a repo must not fail on its catalog,
 * and a repo's own build gate turns `problems` into errors. A key outside the
 * catalog is refused: the catalog describes a template, it never changes what
 * the template renders.
 */
export function parseTemplateCatalogEntry(where: string, value: unknown, problems: string[]): MosaicTemplateCatalogEntry | null {
  if (!isRecord(value)) {
    problems.push(`${where}: the entry must be an object of catalog fields — dropped`);
    return null;
  }
  const entry: MosaicTemplateCatalogEntry = {};
  for (const [key, v] of Object.entries(value)) {
    if (!CATALOG_FIELDS.has(key)) {
      problems.push(`${where}: "${key}" is not a catalog field (${[...MOSAIC_TEMPLATE_CATALOG_FIELDS, "props"].join(", ")}) — a catalog describes a template, it never changes what it renders`);
      continue;
    }
    switch (key as MosaicTemplateCatalogField | "props") {
      case "label":
      case "description":
        if (nonEmpty(v)) (entry as Record<string, unknown>)[key] = v;
        else problems.push(`${where}: "${key}" must be a non-empty string — dropped`);
        break;
      case "tags":
      case "platforms":
      case "channels":
        if (isStringList(v)) (entry as Record<string, unknown>)[key] = [...v];
        else problems.push(`${where}: "${key}" must be a list of non-empty strings — dropped`);
        break;
      case "internal":
      case "primitive":
        if (typeof v === "boolean") (entry as Record<string, unknown>)[key] = v;
        else problems.push(`${where}: "${key}" must be true or false — dropped`);
        break;
      case "preview":
        if (isRecord(v)) entry.preview = { ...v } as MosaicTemplateCatalogEntry["preview"];
        else problems.push(`${where}: "preview" must be an object — dropped`);
        break;
      case "deprecated": {
        const d = parseDeprecation(where, v, problems);
        if (d) entry.deprecated = d;
        break;
      }
      case "props": {
        if (!isRecord(v)) {
          problems.push(`${where}: "props" must map prop keys (dotted, as propsSchema nests them) to presentation — dropped`);
          break;
        }
        const props: Record<string, MosaicTemplatePropCatalog> = {};
        for (const [propKey, pv] of Object.entries(v)) {
          const p = parsePropCatalog(`${where}: props.${propKey}`, pv, problems);
          if (p) props[propKey] = p;
        }
        entry.props = props;
        break;
      }
    }
  }
  return entry;
}

/** A parsed catalog plus everything wrong with it (empty when it is clean). */
export type ParsedTemplateCatalog = {
  file: MosaicTemplateCatalogFile;
  problems: string[];
};

/**
 * Parse a WIRE catalog (`template-catalog.json`). An unknown `schemaVersion`
 * yields no entries (a future format is not guessed at).
 */
export function parseTemplateCatalogFile(raw: unknown): ParsedTemplateCatalog {
  const problems: string[] = [];
  const file: MosaicTemplateCatalogFile = { schemaVersion: 1, templates: {} };
  if (!isRecord(raw)) {
    problems.push(`${TEMPLATE_CATALOG_FILE} must be a JSON object`);
    return { file, problems };
  }
  if (raw.schemaVersion !== 1) {
    problems.push(`${TEMPLATE_CATALOG_FILE} has unsupported schemaVersion ${JSON.stringify(raw.schemaVersion)} (expected 1) — no entries read`);
    return { file, problems };
  }
  if (!isRecord(raw.templates)) {
    problems.push(`${TEMPLATE_CATALOG_FILE}: "templates" must map template ids to entries`);
    return { file, problems };
  }
  for (const [id, value] of Object.entries(raw.templates)) {
    const entry = parseTemplateCatalogEntry(id, value, problems);
    if (entry) file.templates[id] = entry;
  }
  return { file, problems };
}

/** A parsed catalog SIDECAR: the template it names, its entry, and everything wrong with it. */
export type ParsedTemplateCatalogSidecar = {
  templateId: string | null;
  entry: MosaicTemplateCatalogEntry;
  problems: string[];
};

/** Parse one `<name>.catalog.json` ({ schemaVersion: 1, templateId, …catalog fields }). */
export function parseTemplateCatalogSidecar(raw: unknown, where = "catalog sidecar"): ParsedTemplateCatalogSidecar {
  const problems: string[] = [];
  if (!isRecord(raw)) return { templateId: null, entry: {}, problems: [`${where} must be a JSON object`] };
  if (raw.schemaVersion !== 1) {
    return { templateId: null, entry: {}, problems: [`${where} has unsupported schemaVersion ${JSON.stringify(raw.schemaVersion)} (expected 1) — not read`] };
  }
  const templateId = nonEmpty(raw.templateId) ? raw.templateId : null;
  if (!templateId) problems.push(`${where}: "templateId" must name the template this sidecar describes`);
  const { schemaVersion: _v, templateId: _id, ...fields } = raw;
  const entry = parseTemplateCatalogEntry(templateId ?? where, fields, problems) ?? {};
  return { templateId, entry, problems };
}

/** True when two deprecations say the same thing (reason, replacement, since). */
export function sameTemplateDeprecation(
  a: MosaicTemplateDeprecation | undefined,
  b: MosaicTemplateDeprecation | undefined,
): boolean {
  if (!a || !b) return a === b;
  return a.reason === b.reason && String(a.replacement ?? "") === String(b.replacement ?? "") && a.since === b.since;
}

/* ── the as-written view ─────────────────────────────────────────────────── */

function carried(template: object): Authored | null {
  const c = (template as Record<symbol, unknown>)[TEMPLATE_CATALOG_AUTHORED_KEY];
  return isRecord(c) && isRecord(c.fields) ? (c as unknown as Authored) : null;
}

/**
 * The catalog fields a template's FILE declares (own properties with a value) —
 * the legacy form since 0.3.1. A {@link applyTemplateCatalogEntry} copy answers
 * with its file's values, not the catalog's.
 */
export function authoredCatalogFields(template: object): Partial<Record<MosaicTemplateCatalogField, unknown>> {
  const c = carried(template);
  if (c) return { ...c.fields };
  const out: Partial<Record<MosaicTemplateCatalogField, unknown>> = {};
  for (const field of MOSAIC_TEMPLATE_CATALOG_FIELDS) {
    if (Object.prototype.hasOwnProperty.call(template, field) && (template as Record<string, unknown>)[field] !== undefined) {
      out[field] = (template as Record<string, unknown>)[field];
    }
  }
  return out;
}

/** The `propsSchema` a template's FILE declares (the pre-catalog one, for a merged copy). */
export function authoredPropsSchema(template: object): unknown {
  const c = carried(template);
  return c ? c.propsSchema : (template as Record<string, unknown>).propsSchema;
}

/** Where each prop presentation field lives in a prop definition. */
const PROP_FIELD_PATH: Record<keyof MosaicTemplatePropCatalog, readonly string[]> = {
  label: ["meta", "ui", "label"],
  description: ["description"],
  placeholder: ["meta", "control", "placeholder"],
  order: ["meta", "ui", "order"],
  primary: ["meta", "ui", "primary"],
  collapsedByDefault: ["meta", "ui", "collapsedByDefault"],
};

const readPath = (obj: unknown, path: readonly string[]): unknown =>
  path.reduce<unknown>((o, k) => (isRecord(o) ? o[k] : undefined), obj);

/**
 * The prop presentation a template's FILE declares, as `<dotted key>.<field>`
 * (`quote.description`, `titles.title.label`) — the legacy form since 0.3.1.
 */
export function authoredPropCopy(template: object): string[] {
  const out: string[] = [];
  const walk = (schema: unknown, prefix: string): void => {
    if (!isRecord(schema)) return;
    for (const [key, def] of Object.entries(schema)) {
      if (!isRecord(def)) continue;
      const dotted = prefix ? `${prefix}.${key}` : key;
      for (const field of MOSAIC_TEMPLATE_PROP_CATALOG_FIELDS) {
        if (readPath(def, PROP_FIELD_PATH[field]) !== undefined) out.push(`${dotted}.${field}`);
      }
      if (isRecord(def.fields)) walk(def.fields, dotted);
    }
  };
  walk(authoredPropsSchema(template), "");
  return out.sort();
}

/**
 * Prop keys a catalog entry describes that the template's `propsSchema` does
 * not have (a typo, or a prop that was never there) — a gate's finding.
 */
export function unknownCatalogProps(template: object, entry: MosaicTemplateCatalogEntry): string[] {
  const schema = authoredPropsSchema(template);
  return Object.keys(entry.props ?? {}).filter((dotted) => {
    let level: unknown = schema;
    const segs = dotted.split(".");
    for (let i = 0; i < segs.length; i++) {
      const def = isRecord(level) ? level[segs[i]!] : undefined;
      if (!isRecord(def)) return true;
      level = def.fields;
    }
    return false;
  }).sort();
}

/**
 * Split a props schema into what a template's CODE keeps (types, constraints,
 * controls — a schema with no presentation) and what its catalog sidecar holds
 * (`props`: each prop's label, hint, placeholder, order, primary,
 * collapsedByDefault, dotted as the schema nests them). The input is never
 * mutated; empty `meta.ui` / `meta.control` / `meta` objects left behind are
 * dropped. The migration tool of the 0.3.1 convention, and how a library
 * schema with baked-in copy (a factory's) serves a catalog-convention repo.
 */
export function splitPropPresentation(schema: unknown): { schema: Record<string, unknown>; props: Record<string, MosaicTemplatePropCatalog> } {
  const props: Record<string, MosaicTemplatePropCatalog> = {};
  const strip = (level: unknown, prefix: string): Record<string, unknown> => {
    const out: Record<string, unknown> = {};
    if (!isRecord(level)) return out;
    for (const [key, def] of Object.entries(level)) {
      if (!isRecord(def)) { out[key] = def; continue; }
      const dotted = prefix ? `${prefix}.${key}` : key;
      const copy: Record<string, unknown> = { ...def };
      const entry: MosaicTemplatePropCatalog = {};
      for (const field of MOSAIC_TEMPLATE_PROP_CATALOG_FIELDS) {
        const value = readPath(copy, PROP_FIELD_PATH[field]);
        if (value !== undefined) (entry as Record<string, unknown>)[field] = value;
      }
      if ("description" in copy) delete copy.description;
      if (isRecord(copy.meta)) {
        const meta: Record<string, unknown> = { ...copy.meta };
        if (isRecord(meta.ui)) {
          const ui: Record<string, unknown> = { ...meta.ui };
          for (const k of ["label", "order", "primary", "collapsedByDefault"]) delete ui[k];
          if (Object.keys(ui).length) meta.ui = ui; else delete meta.ui;
        }
        if (isRecord(meta.control)) {
          const control: Record<string, unknown> = { ...meta.control };
          delete control.placeholder;
          if (Object.keys(control).length) meta.control = control; else delete meta.control;
        }
        if (Object.keys(meta).length) copy.meta = meta; else delete copy.meta;
      }
      if (isRecord(copy.fields)) copy.fields = strip(copy.fields, dotted);
      if (Object.keys(entry).length) props[dotted] = entry;
      out[key] = copy;
    }
    return out;
  };
  return { schema: strip(schema, ""), props };
}

/** A props schema with no presentation — {@link splitPropPresentation}'s `schema`. */
export function stripPropPresentation(schema: unknown): Record<string, unknown> {
  return splitPropPresentation(schema).schema;
}

/* ── applying ────────────────────────────────────────────────────────────── */

/** A copy of `schema` with each prop entry's presentation written into its definition. */
function applyPropCatalog(schema: unknown, props: Readonly<Record<string, MosaicTemplatePropCatalog>>): unknown {
  if (!isRecord(schema)) return schema;
  const root: Record<string, unknown> = { ...schema };
  for (const [dotted, p] of Object.entries(props)) {
    const segs = dotted.split(".");
    let level: Record<string, unknown> = root;
    let def: Record<string, unknown> | null = null;
    for (let i = 0; i < segs.length; i++) {
      const cur = level[segs[i]!];
      if (!isRecord(cur)) { def = null; break; }
      def = { ...cur };
      level[segs[i]!] = def;
      if (i < segs.length - 1) {
        if (!isRecord(def.fields)) { def = null; break; }
        def.fields = { ...def.fields };
        level = def.fields as Record<string, unknown>;
      }
    }
    if (!def) continue; // an unknown prop: the gate reports it (unknownCatalogProps)
    for (const field of MOSAIC_TEMPLATE_PROP_CATALOG_FIELDS) {
      const value = p[field];
      if (value === undefined) continue;
      const path = PROP_FIELD_PATH[field];
      let node: Record<string, unknown> = def;
      for (let i = 0; i < path.length - 1; i++) {
        const next = isRecord(node[path[i]!]) ? { ...(node[path[i]!] as Record<string, unknown>) } : {};
        node[path[i]!] = next;
        node = next;
      }
      node[path[path.length - 1]!] = value;
    }
  }
  return root;
}

/**
 * A copy of `template` with a catalog `entry` applied — catalog-first: every
 * field the entry names overrides the template's own, and each `props` entry is
 * written into a copy of the prop's definition. What the template's FILE
 * declared (its catalog fields and its original `propsSchema`) is kept under
 * {@link TEMPLATE_CATALOG_AUTHORED_KEY}. Every other own property (render
 * functions, symbols, non-enumerables) is the original's; the input is never
 * mutated.
 */
export function applyTemplateCatalogEntry<T extends object>(template: T, entry: MosaicTemplateCatalogEntry): T {
  const authored: Authored = { fields: authoredCatalogFields(template), propsSchema: authoredPropsSchema(template) };
  const descriptors = Object.getOwnPropertyDescriptors(template) as PropertyDescriptorMap;
  for (const field of MOSAIC_TEMPLATE_CATALOG_FIELDS) {
    const value = entry[field];
    if (value === undefined) continue;
    const copy = Array.isArray(value) ? [...value] : isRecord(value) ? { ...value } : value;
    descriptors[field] = { value: copy, enumerable: true, writable: true, configurable: true };
  }
  if (entry.props && Object.keys(entry.props).length > 0) {
    const current = (template as Record<string, unknown>).propsSchema;
    descriptors.propsSchema = { value: applyPropCatalog(current, entry.props), enumerable: true, writable: true, configurable: true };
  }
  descriptors[TEMPLATE_CATALOG_AUTHORED_KEY as unknown as string] = {
    value: authored,
    enumerable: false,
    writable: false,
    configurable: true,
  };
  return Object.create(Object.getPrototypeOf(template), descriptors) as T;
}

/** What {@link withTemplateCatalog} did. */
export type TemplateCatalogMerge<T> = {
  /** The templates, in order — catalogued ones as copies with the entry applied. */
  templates: T[];
  /** Ids that took a catalog entry. */
  applied: string[];
  /** Catalog ids none of the templates carry. */
  unknown: string[];
};

/**
 * Merge a catalog into a list of templates — what the repo loader does before a
 * host registers them, so every host reads `template.tags`, `.deprecated`, a
 * prop's label and hint, … exactly as before, catalog-first.
 */
export function withTemplateCatalog<T extends { id?: unknown }>(
  templates: readonly T[],
  entries: Readonly<Record<string, MosaicTemplateCatalogEntry>>,
): TemplateCatalogMerge<T> {
  const merge: TemplateCatalogMerge<T> = { templates: [], applied: [], unknown: [] };
  const seen = new Set<string>();
  for (const t of templates) {
    const id = String(t?.id ?? "");
    seen.add(id);
    const entry = entries[id];
    if (!entry) { merge.templates.push(t); continue; }
    merge.templates.push(applyTemplateCatalogEntry(t, entry));
    merge.applied.push(id);
  }
  for (const id of Object.keys(entries)) if (!seen.has(id)) merge.unknown.push(id);
  merge.applied.sort();
  merge.unknown.sort();
  return merge;
}

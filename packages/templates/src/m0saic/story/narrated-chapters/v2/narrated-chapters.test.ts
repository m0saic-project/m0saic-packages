import type { MosaicDocument, MosaicRenderableFile } from "@m0saic/types";
import { ctxFor, handlesOf, vnextSuite } from "../../../../__tests__/vnextSuite";
import { DEMO_STORY } from "../v1/demo-fixture";
import { NarratedChapters } from "../v1/narrated-chapters";
import { NarratedChaptersV2 } from "./narrated-chapters";

const OWN_STORY = {
  schemaVersion: 1,
  title: "Two Rooms",
  subtitle: "A short tour",
  brand: { accentColor: "#ff5500", backgroundColor: "#101010", textColor: "#fafafa" },
  outputs: ["landscape", "portrait"],
  sections: [
    { id: "a", title: "The Hall", narrationText: "Come in. Mind the step.", overrides: { durationMs: 2000 } },
    {
      id: "b",
      title: "The Study",
      narrationText: "Books, mostly.",
      cues: [{ startMs: 0, endMs: 900, text: "Books," }, { startMs: 900, endMs: 1800, text: "mostly." }],
      overrides: { durationMs: 1800 },
    },
  ],
};

vnextSuite({
  next: NarratedChaptersV2,
  prev: NarratedChapters,
  cases: [
    { name: "an own story, both aspects, explicit cues", props: { story: OWN_STORY } },
    { name: "the story as a JSON string", props: { story: JSON.stringify(OWN_STORY) } },
    { name: "portrait canvas (the demo adopts it)", props: {}, w: 1080, h: 1920 },
    { name: "a broken manifest is still the error card", props: { story: { sections: "nope" } } },
  ],
  bound: ["story"],
  unbound: {
    mediaPaths: "probe mirror (machine-generated by `story-studio build`)",
    projectDir: "informational (shortens paths in diagnostics)",
  },
});

describe("@m0saic/story/narrated-chapters/v2 — handles", () => {
  type Entry = { propKey: string; path?: Array<string | number>; kind?: string };
  type Labelled = { editor?: { label?: string; bindings?: Entry[] } };
  const sceneDocs = (file: MosaicRenderableFile): MosaicDocument[] =>
    ((file as { steps?: Array<{ file?: { steps?: Array<{ file?: MosaicDocument }> } }> }).steps ?? []).flatMap((v) => (v.file?.steps ?? []).map((s) => s.file!));
  const handlesByLabel = (file: MosaicRenderableFile): Record<string, string[]> => {
    const out: Record<string, string[]> = {};
    for (const doc of sceneDocs(file)) {
      for (const s of doc.sources as Labelled[]) {
        if (s.editor?.bindings) out[s.editor.label!] = s.editor.bindings.map((b) => `${(b.path ?? []).join(".")}:${b.kind}`);
      }
    }
    return out;
  };
  const D = NarratedChaptersV2.defaultProps as Record<string, unknown>;

  it("the form is seeded with the demo manifest — and renders exactly what v1's empty form rendered", async () => {
    expect(D.story).toBe(DEMO_STORY);
    const ctx = ctxFor(NarratedChaptersV2);
    const next = await NarratedChaptersV2.render({ ...D } as never, ctx);
    const prev = await NarratedChapters.render({} as never, ctx);
    const strip = (f: unknown) => JSON.parse(JSON.stringify(f, (k, v) => (k === "editor" && v && typeof v === "object" && "bindings" in v ? { ...v, bindings: undefined } : v)));
    expect(strip(next)).toEqual(strip(prev));
  });

  it("cards and captions carry the story's own leaves (v1 bound nothing)", async () => {
    const file = await NarratedChaptersV2.render({ story: OWN_STORY } as never, ctxFor(NarratedChaptersV2));
    expect(handlesByLabel(file)).toEqual({
      "title/heading": ["title:string", "brand.textColor:color"],
      "title/sub": ["subtitle:string"],
      "s0-card/kicker": ["brand.accentColor:color"],
      "s0-card/heading": ["sections.0.title:string", "brand.textColor:color"],
      "s0-body/captions": ["sections.0.narrationText:string", "brand.textColor:color"],
      "s1-card/kicker": ["brand.accentColor:color"],
      "s1-card/heading": ["sections.1.title:string", "brand.textColor:color"],
      // s1 brings its own timed cues: its captions are not one string to edit.
      "outro/heading": ["title:string", "brand.textColor:color"],
      "outro/sub": ["subtitle:string"],
    });
  });

  it("every variant's scenes carry them, and nothing is rejected", async () => {
    const ctx = ctxFor(NarratedChaptersV2);
    const file = await NarratedChaptersV2.render({ story: OWN_STORY } as never, ctx);
    const variants = (file as { steps?: unknown[] }).steps ?? [];
    expect(variants).toHaveLength(2);
    const bound = sceneDocs(file).filter((doc) => (doc.sources as Labelled[]).some((s) => s.editor?.bindings));
    expect(bound.length).toBe(2 * 5); // per variant: title, two section cards, s0's captions, outro (s1's body carries none)
    for (const doc of sceneDocs(file)) {
      const h = handlesOf(doc, NarratedChaptersV2, ctx);
      expect(h.rejected).toEqual([]);
    }
  });

  it("a story that is NOT the prop's own object has no leaf to write: a JSON string, or the bare bag", async () => {
    const ctx = ctxFor(NarratedChaptersV2);
    const asString = await NarratedChaptersV2.render({ story: JSON.stringify(OWN_STORY) } as never, ctx);
    expect(handlesByLabel(asString)).toEqual({});
    const bare = await NarratedChaptersV2.render({ ...OWN_STORY } as never, ctx);
    expect(handlesByLabel(bare)).toEqual({});
  });

  it("`--props @story.json` still wins over the seeded demo (the bag's own sections, beside the merged default)", async () => {
    const ctx = ctxFor(NarratedChaptersV2);
    // What a host hands render(): the defaults merged under the user's bag.
    const merged = await NarratedChaptersV2.render({ ...D, ...OWN_STORY } as never, ctx);
    const v1 = await NarratedChapters.render({ ...OWN_STORY } as never, ctx);
    expect(JSON.stringify(merged)).toContain("Two Rooms");
    expect(JSON.stringify(merged)).not.toContain("Every Level of a City Block");
    expect(merged).toEqual(v1);
    // A cloned seed (hosts copy defaults) is still recognised as the seed.
    const cloned = await NarratedChaptersV2.render({ story: JSON.parse(JSON.stringify(DEMO_STORY)), ...OWN_STORY } as never, ctx);
    expect(cloned).toEqual(v1);
    // …but an explicit story of the user's own is never overridden by stray bag keys.
    const explicit = await NarratedChaptersV2.render({ story: OWN_STORY, sections: DEMO_STORY.sections } as never, ctx);
    expect(JSON.stringify(explicit)).toContain("Two Rooms");
  });
});

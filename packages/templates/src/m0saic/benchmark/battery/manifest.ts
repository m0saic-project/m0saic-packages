import type { BenchmarkSet, VideoCodec } from "@m0saic/types";

/**
 * The benchmark battery manifest — the list of frozen `.mosaic` workloads a run
 * can render, grouped by set. This is **pure data** (no node imports), so it is
 * safe to import anywhere; the runner resolves each workload's file under
 * {@link BATTERY_SCENARIOS_SUBDIR} relative to this module's directory.
 *
 * Each workload is an immutable `.mosaic` file (the frozen *output* of a render,
 * not a live template) so numbers stay comparable across machines and over time.
 * The synthetic + media/audio workloads are generated by
 * `tools/bake-benchmark-battery.mjs` (media/audio reference bundled BBB clips
 * under assets/media/); the `real` workloads — captured snapshots of shipped
 * templates — are added as those land.
 */
export type BatteryScenario = {
  /** Stable scenario id; also the per-scenario output basename in a run. */
  id: string;
  set: BenchmarkSet;
  /** Human label shown on the results video. */
  label: string;
  /** Frozen `.mosaic` filename under {@link BATTERY_SCENARIOS_SUBDIR}. */
  file: string;
  /**
   * For `encoders`-set scenarios: the video codec to render this workload with
   * (`make --video-codec`). The same `file` is rendered once per codec so the
   * per-codec speed is directly comparable.
   */
  codec?: VideoCodec;
  /**
   * Provenance for `real`-set scenarios: the shipped template id(s) the frozen
   * workload was captured from / composed of. Records origin, not an invocation
   * target — the run renders the frozen file.
   */
  templateIds?: string[];
  /**
   * Render-duration override (ms) for this scenario (`make --durationMs`). Lets
   * one captured workload be measured at several lengths (short/medium/long) to
   * map how render cost scales with output duration. Omitted → the workload's
   * own baked duration.
   */
  durationMs?: number;
};

/** Directory (relative to this module) holding the frozen `.mosaic` workloads. */
export const BATTERY_SCENARIOS_SUBDIR = "assets/scenarios";

/**
 * Content version per set — the *battery* version, independent of the JSON
 * `schemaVersion`. Bump a set's number whenever its workload list changes
 * (add / remove / swap / recapture) so an older battery is never silently
 * compared against a newer one. Only sets with at least one shipped workload
 * appear here; `real` (and the media/audio additions to `sources`) land later.
 */
export const BENCHMARK_SET_VERSIONS: Partial<Record<BenchmarkSet, number>> = {
  sources: 2, // v2 adds the media + audio workloads (BBB clips)
  geometry: 1,
  duration: 1,
  encoders: 1,
  real: 3, // v3 carves the donut out to the `sloth` tier (was v2: +stat-card)
  sloth: 1, // known complexity blowups (the donut masked-sweep)
  lifetime: 1, // enable-window gating: 3s fade at [27,30] inside a 30s parent
};

/**
 * Three tiers. **standard** sets are quick synthetic/primitive probes (the
 * default run). **heavy** sets render captured REAL templates (charts, video
 * grids) at multiple durations — minutes-long, the truest signal of real-world
 * cost — and are opt-in. **sloth** holds known complexity blowups (the donut's
 * masked-sweep, ~70min at 30s): real workloads whose cost is so pathological
 * they'd dominate a run's wall-clock AND flatten every other bar on the results
 * chart, so they get their own opt-in tier — run them deliberately, on their own.
 */
export const BENCHMARK_STANDARD_SETS: BenchmarkSet[] = ["sources", "geometry", "duration", "encoders"];
export const BENCHMARK_HEAVY_SETS: BenchmarkSet[] = ["real", "lifetime"];
export const BENCHMARK_SLOTH_SETS: BenchmarkSet[] = ["sloth"];

/** A captured workload measured at short / medium / long lengths. */
type RealWorkload = { base: string; label: string; file: string; templateIds: string[] };

/** Captured real-template workloads (the frozen `.mosaic` + its provenance). */
const REAL_WORKLOADS: RealWorkload[] = [
  { base: "real-stat-card", label: "KPI stat-card", file: "real-stat-card.mosaic", templateIds: ["@m0saic/charts/stat-card/v1"] },
  { base: "real-bar-graph", label: "Bar graph", file: "real-bar-graph.mosaic", templateIds: ["@m0saic/charts/bar-graph/v1"] },
  { base: "real-screencap-grid", label: "Screencap grid", file: "real-screencap-grid.mosaic", templateIds: ["@m0saic/media/screencap_grid_mp4/v1"] },
];

/**
 * Sloth workloads — same capture shape as `real`, but their render cost is a
 * known blowup (the donut renders ~31 masked sources every frame; 4234s at 30s
 * on an M1). Kept out of `real` so the report's bar scale stays readable.
 */
const SLOTH_WORKLOADS: RealWorkload[] = [
  { base: "sloth-donut", label: "Donut chart", file: "real-donut.mosaic", templateIds: ["@m0saic/charts/donut/v1"] },
];

/** Short / medium / long render lengths each real / sloth workload is measured at. */
const REAL_DURATIONS: { ms: number; tag: string }[] = [
  { ms: 5000, tag: "5s" },
  { ms: 15000, tag: "15s" },
  { ms: 30000, tag: "30s" },
];

function durationScenarios(workloads: RealWorkload[], set: BenchmarkSet): BatteryScenario[] {
  return workloads.flatMap((w) =>
    REAL_DURATIONS.map((d) => ({
      id: `${w.base}-${d.tag}`,
      set,
      label: `${w.label} · ${d.tag}`,
      file: w.file,
      durationMs: d.ms,
      templateIds: w.templateIds,
    })),
  );
}

const realScenarios = (): BatteryScenario[] => durationScenarios(REAL_WORKLOADS, "real");
const slothScenarios = (): BatteryScenario[] => durationScenarios(SLOTH_WORKLOADS, "sloth");


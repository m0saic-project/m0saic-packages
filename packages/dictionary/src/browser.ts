/**
 * Compose an entry by spreading its metadata.json over a small set of
 * browser-specific overrides. The cast at the end is necessary because
 * TypeScript can't statically prove that imported JSON satisfies the
 * `MosaicDictionaryEntryResolved` discriminated union (the `category`
 * field comes through as a literal string, not the typed union).
 */
function entry(
  meta: object,
  overrides: { m0: string; m0File?: string; preview?: { mode: "image"; src: string } },
): MosaicDictionaryEntryResolved {
  return { ...meta, ...overrides } as unknown as MosaicDictionaryEntryResolved;
}


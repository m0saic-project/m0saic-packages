/**
 * Browser-compatible dictionary export.
 *
 * ## Import strategy
 *
 * Consumers should always import from `@m0saic/dictionary`:
 *
 *   import { entries, generators, resolveM0saic } from "@m0saic/dictionary";
 *
 * - **Browser bundles** (webpack, vite, etc.): the bundler resolves to this
 *   file via the `"browser"` field in package.json. DSL strings are inlined
 *   — light entries as literals, brand entries from their generated
 *   `m0.json` (tools/validate.js, ≤ 40 KB). Only the m-33 bitmap ships
 *   `m0: ""` and must be resolved via `resolveM0saic(entry)`, which fetches
 *   from the server.
 *
 * - **Node / CLI**: resolves to `index.ts` which reads .m0 files from disk.
 *
 * Both exports use the same `MosaicDictionaryEntryResolved` type. The only
 * difference is how the m0saic payload is loaded (inlined vs fs.readFileSync).
 *
 * Do NOT import this file directly — use `@m0saic/dictionary`.
 * The bundler handles resolution automatically.
 *
 * ## How each entry is constructed
 *
 * The dictionary's source of truth for metadata (title, description, tags,
 * `complexity`, `feasibility`, `sourceResolution`, etc.) is each entry's
 * `metadata.json` file. The build script (`tools/validate.js`) writes the
 * precomputed `complexity`/`feasibility`/`sourceResolution` fields back into
 * those files on every build, so they're always in sync with the .m0.
 *
 * This file imports each entry's metadata.json and only overrides:
 *   - `m0`: inline DSL string for light entries, "" for heavy entries
 *   - `m0File`: path to the .m0 file (heavy entries only, for lazy resolve)
 *   - `preview.src`: rewritten to be relative to the dictionary dist root
 *     (the path in metadata.json is relative to the entry directory)
 *
 * Adding a new entry: create the metadata.json + m0saic.m0 in
 * `src/entries/<category>/<slug>/`, run `npm run dictionary:validate` (which
 * populates the precomputed fields), then add an import + entry stub here.
 */

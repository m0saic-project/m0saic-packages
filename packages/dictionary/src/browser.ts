// Auto-register the official dictionary (browser entry point)
const byId = Object.fromEntries(ENTRIES.map((e) => [e.id, e])) as Record<string, MosaicDictionaryEntryResolved>;
registry.register({
  name: "@m0saic/dictionary",
  all: ENTRIES,
  byId,
  // Rank sets ride in metadata.json, so they are on web — same lookup as the
  // node entry (`entries/__generated__.ts`). Until 2026-09-16 this threw
  // "not available in browser bundle", which took Brand Marks down on web.
  getRankSet(entryId, name) {
    const entry = byId[entryId];
    if (!entry) throw new Error(`Dictionary entry not found: "${entryId}"`);
    const rs = entry.rankSets?.[name];
    if (!rs) throw new Error(`Rank set not found: entry="${entryId}" name="${name}"`);
    return rs;
  },
  // Named mask SETS are resolved from mask files at node load time
  // (`maskSetsResolved`); nothing populates them here, so the same
  // "not found" the node entry gives for a missing set. Per-frame `masks`
  // (what every shipped template uses) are on the entry itself.
  getMaskSet(entryId, name) {
    const entry = byId[entryId];
    if (!entry) throw new Error(`Dictionary entry not found: "${entryId}"`);
    const ms = entry.maskSetsResolved?.[name];
    if (!ms) throw new Error(`Mask set not found: entry="${entryId}" name="${name}" (named mask sets are not bundled for the browser)`);
    return ms;
  },
  assetsBasePath: "/dictionary",
});


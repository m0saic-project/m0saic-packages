// Inline the INCLUDED starter media — `assets/starter/<role>.svg` — into a
// browser-safe TypeScript module, `src/media/starterSvgInline.ts`, so the
// browser twin of `defaultMedia` (`defaultMedia.browser.ts`) can hand a
// template the same six stand-ins as `data:` URIs without a filesystem.
//
// Run after `tools/mint-starter-svg.mjs` (the files are the source of truth;
// `src/media/defaultMedia.browser.test.ts` fails when the two drift):
//
//   node packages/template-utils/tools/inline-starter-svg.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC_DIR = path.join(PKG, "assets", "starter");
const OUT = path.join(PKG, "src", "media", "starterSvgInline.ts");

const ROLES = ["portrait", "landscape", "square", "facecam", "avatar", "logo"];

const entries = ROLES.map((role) => {
  const text = fs.readFileSync(path.join(SRC_DIR, `${role}.svg`), "utf8").trim();
  return `  ${role}: ${JSON.stringify(text)},`;
});

const module = `// GENERATED by tools/inline-starter-svg.mjs from assets/starter/*.svg — do not
// edit by hand; re-run the tool after tools/mint-starter-svg.mjs. The browser
// twin of defaultMedia serves these as \`data:image/svg+xml\` URIs.
/* eslint-disable */

/** The six starter SVGs, keyed by slot role — byte-identical to the files. */
export const STARTER_SVG_TEXT = {
${entries.join("\n")}
} as const;
`;

fs.writeFileSync(OUT, module, "utf8");
console.log(`[inline-starter-svg] wrote ${path.relative(PKG, OUT)} (${ROLES.length} roles)`);
